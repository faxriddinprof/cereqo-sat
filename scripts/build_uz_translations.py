def po_quote(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    root = Path(__file__).resolve().parents[1]
    po_path = root / "locale" / "uz" / "LC_MESSAGES" / "django.po"
    mo_path = po_path.with_suffix(".mo")
    po_path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        'msgid ""\nmsgstr ""\n'
        '"Project-Id-Version: Cereqo 1.0\\n"\n'
        '"Language: uz\\n"\n'
        '"Content-Type: text/plain; charset=UTF-8\\n"\n'
        '"Content-Transfer-Encoding: 8bit\\n"\n'
        '"Plural-Forms: nplurals=1; plural=0;\\n"\n\n'
    )
    entries = [header]
    for source, translated in sorted(TRANSLATIONS.items()):
        entries.append(f"msgid {po_quote(source)}\nmsgstr {po_quote(translated)}\n\n")
    po_path.write_text("".join(entries), encoding="utf-8")
    subprocess.run(["msgfmt", "-o", str(mo_path), str(po_path)], check=True)
    print(f"Built {len(TRANSLATIONS)} Uzbek translations")


if __name__ == "__main__":
    main()
